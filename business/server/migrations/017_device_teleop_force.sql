-- 强制接管标记：遥控器（硬件通道，`ctrl_source = 3`）抢权时仍允许平台接管。
--
-- 现场问题：遥控器用了之后直接关电源，本体可能还要一会儿（甚至一直）把
-- `ctrl_source` 报成 3。此时健康门禁会把「远程接管」和摇杆全部拒掉，平台只能
-- 等状态自己刷新，运维看起来就是「遥控器都关了还是不能接管」。
--
-- 语义：
--   0 = 常规接管，`ctrl_source = 3` 时拒绝接管与摇杆（默认）；
--   1 = 运维显式强制接管（前端二次确认），跳过 `ctrl_source` 这一条门禁，
--       其余门禁（离线 / sdk_node / 急停 / 卧倒）照旧。释放接管或设备掉线时清零。
ALTER TABLE devices ADD COLUMN teleop_force INTEGER NOT NULL DEFAULT 0;
